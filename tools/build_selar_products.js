#!/usr/bin/env node
// Regenerates api/_lib/selarProducts.js from site/fluency-data.js (the single source of truth for guides and prices).
// Run from the repo root after adding or changing a guide:  node tools/build_selar_products.js
const vm = require('vm'), fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const w = {};
vm.runInNewContext(fs.readFileSync(path.join(root, 'site/fluency-data.js'), 'utf8'), { window: w, document: {}, localStorage: {}, console });
const guides = w.FluencyData.GUIDES.filter((g) => g.selar).map((g) => ({ code: g.selar, id: g.id, name: g.name, full: g.full, usd: g.price }));
const out = `// GENERATED by tools/build_selar_products.js from site/fluency-data.js. Do not edit by hand.
// Selar product code -> guide, with the list price in US dollars (used to sanity-check order amounts).
module.exports = ${JSON.stringify(guides, null, 2)};
`;
fs.writeFileSync(path.join(root, 'api/_lib/selarProducts.js'), out);
console.log('wrote api/_lib/selarProducts.js with ' + guides.length + ' guides');
